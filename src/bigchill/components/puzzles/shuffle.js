// Fisher-Yates - used wherever a puzzle needs a fresh randomised layout
// (grid cell order, icon arrangement) without mutating the input.
export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
